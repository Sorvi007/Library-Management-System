-- Body -- 

CREATE OR REPLACE PACKAGE BODY LibraryManagement  
IS  
-- procedure for borrowing the book -- 

PROCEDURE BorrowBook( 
	p_book_id IN Books.book_id%Type, 
    p_member_id IN Members.member_id%Type, 
    p_staff_id IN Staffs.staff_id%Type, 
    p_due_date IN Transactions.book_due_date%Type
    )  
IS  
	v_available_quantity NUMBER;
	v_transaction_id Transactions.transaction_id%Type; 
BEGIN 
	SELECT quantity_available INTO v_available_quantity 
	FROM Books 
	WHERE book_id = p_book_id; 
	
	if v_available_quantity <= 0 THEN 
	RAISE_APPLICATION_ERROR(-20001, 'Book is not available in stock'); 
	END IF; 

	INSERT INTO Transactions(book_id, member_id, staff_id, book_due_date)  
	VALUES(p_book_id, p_member_id, p_staff_id, sysdate + 14)
	RETURNING transaction_id INTO v_transaction_id; 
               
	UPDATE Books 
	SET quantity_available = quantity_available - 1, 
		quantity_borrowed = quantity_borrowed + 1 
	WHERE book_id = p_book_id; 
	DBMS_OUTPUT.PUT_LINE('Book borrowed successfully! Transaction id: ' || v_transaction_id) ; 
    Commit; 
               
	EXCEPTION 
		WHEN OTHERS THEN 
		DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM); 
        Rollback; 
               
		END BorrowBook; 
-- procedure for returning the book -- 

PROCEDURE ReturnBook( 
    p_transaction_id IN Transactions.transaction_id%type) 
IS 
    v_book_id Transactions.book_id%Type; 
	v_member_id Transactions.member_id%Type;  
	v_due_date Transactions.book_due_date%Type;
	v_return_date Date := sysdate;
	v_late_charge NUMBER(10,2) := 0;
	v_status Transactions.status%Type;  
BEGIN 
	SELECT book_id, member_id, book_due_date, status 
	INTO v_book_id, v_member_id, v_due_date, v_status 
	FROM Transactions 
	WHERE transaction_id = p_transaction_id AND status = 'borrowed'; 
     
	-- Late charge calculation --
	IF  v_return_date > v_due_date THEN  
		v_late_charge := (v_return_date - v_due_date)* 10;
    END IF;
	
		UPDATE Transactions 
		SET book_return_date = v_return_date, status = 'returned', late_charge = v_late_charge, late_charge_due = v_late_charge
		WHERE transaction_id = p_transaction_id;
         
        DBMS_OUTPUT.PUT_LINE('Book returned successfully! Late charge pending: ' || v_late_charge); 
        Commit; 
         
	EXCEPTION 
		WHEN NO_DATA_FOUND THEN 
			RETURN; 
			DBMS_OUTPUT.PUT_LINE('ERROR: Transaction does not exist or Invalid'); 
		WHEN OTHERS THEN 
			Rollback; 
			DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM); 
         
END ReturnBook; 

-- procedure to payfine -- 
 
PROCEDURE PayFine(
	p_transaction_id IN Transactions.transaction_id%type,
	p_payment_mode IN Transactions.payment_mode%Type,
	p_amount_paid IN NUMBER) 
IS 
	v_late_charge_due Transactions.late_charge_due%Type;
	v_new_late_charge_due NUMBER; 
BEGIN 
	SELECT late_charge_due INTO v_late_charge_due 
	FROM Transactions
	WHERE transaction_id = p_transaction_id;
		
	-- check if partial or full payment --
	IF p_amount_paid < v_late_charge_due THEN
	v_new_late_charge_due := v_late_charge_due - p_amount_paid;
	
		UPDATE Transactions 
		SET late_charge_due = v_new_late_charge_due
		WHERE transaction_id = p_transaction_id; 
		DBMS_OUTPUT.PUT_LINE('Partial payment received. Remaining fine: ' || v_new_late_charge_due);
	ELSE 
		UPDATE Transactions 
		SET late_charge_due = 0
		WHERE transaction_id = p_transaction_id;
		DBMS_OUTPUT.PUT_LINE('Full payment paid');
	END IF;
	
		UPDATE Transactions
		SET payment_mode = UPPER(p_payment_mode)
		WHERE transaction_id = p_transaction_id;
		COMMIT;
		 
    EXCEPTION 
		WHEN NO_DATA_FOUND THEN
			DBMS_OUTPUT.PUT_LINE('ERROR: Transaction ID not found');
        RETURN;
		
        WHEN OTHERS THEN 
            DBMS_OUTPUT.PUT_LINE('ERROR: ' || SQLERRM); 
            Rollback;  
END PayFine; 
END LibraryManagement; 

-- Triggers -- 

CREATE OR REPLACE TRIGGER UpdateBookQuantityAfterReturn  
AFTER UPDATE OF status ON Transactions  
FOR EACH ROW  
BEGIN 
	IF :NEW.status = 'returned' THEN  
		UPDATE Books  
		SET quantity_available = quantity_available + 1, quantity_borrowed = quantity_borrowed - 1 
		WHERE book_id = :NEW.book_id;  
	END IF; 
 END UpdateBookQuantityAfterReturn; 


