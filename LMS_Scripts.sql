-- TABLES -- 

CREATE TABLE Authors(
author_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
author_name VARCHAR2(255) NOT NULL,
genre VARCHAR2(100),
date_of_birth DATE,
nationality VARCHAR2(100),
website VARCHAR2(255)
);

create table Books( 
book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
title VARCHAR2(255) NOT NULL, 
author_id NUMBER REFERENCES Authors(author_id)NOT NULL,
genre VARCHAR2(100), 
Publisher VARCHAR(255),
publication_date DATE, 
quantity_available NUMBER(5) DEFAULT 0 CHECK(quantity_available >= 0), 
quantity_borrowed NUMBER(5) DEFAULT 0 CHECK (quantity_borrowed >= 0) ); 

CREATE TABLE Members( 
member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
first_name VARCHAR2(100) NOT NULL, 
last_name VARCHAR2(100) NOT NULL, 
email VARCHAR2(100) UNIQUE NOT NULL, 
phone_number VARCHAR2(15) NOT NULL, 
address VARCHAR2(255), 
membership_date DATE DEFAULT SYSDATE NOT NULL, 
renewal_date DATE, 
membership_status VARCHAR2(20) DEFAULT 'active' CHECK (membership_status IN('ACTIVE', 'EXPIRED', 'SUSPENDED')) ); 

CREATE TABLE Staffs( 
staff_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
first_name VARCHAR2(100) NOT NULL, 
last_name VARCHAR2(100) NOT NULL, 
phone VARCHAR2(15), 
email VARCHAR2(100), 
address VARCHAR2(255), 
hire_date DATE NOT NULL, 
salary NUMBER(10, 2) NOT NULL, 
department VARCHAR2(100) NOT NULL ); 

CREATE TABLE Transactions ( 
transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
book_id NUMBER NOT NULL REFERENCES Books(book_id), 
member_id NUMBER NOT NULL REFERENCES Members(member_id), 
staff_id NUMBER NOT NULL REFERENCES Staffs(staff_id), 
borrow_date DATE DEFAULT SYSDATE NOT NULL, 
book_due_date DATE NOT NULL, 
book_return_date DATE, 
status VARCHAR2(15) DEFAULT 'borrowed' CHECK (status IN ('borrowed', 'returned')) )
late_charge NUMBER(10,2) DEFAULT 0, 
late_charge_due NUMBER(10,2) DEFAULT 0 CHECK (fine_due >= 0)
payment_mode VARCHAR2(20) NULL CHECK (UPPER(payment_mode) IN ('Cash', 'Card', 'UPI')); 


